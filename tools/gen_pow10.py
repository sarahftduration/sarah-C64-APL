"""Generate asm/pow10.inc: powers of ten as 32-bit mantissa + binary exponent.

10^e = m * 2^b with m in [2^31, 2^32), rounded to nearest. Exact for 0 <= e <= 13.
Stored as six 86-byte arrays indexed by e + 47: m0..m3 (little endian), bl, bh.
"""
from fractions import Fraction

LO, HI = -47, 38


def entry(e):
    t = Fraction(10) ** e
    b = t.numerator.bit_length() - t.denominator.bit_length() - 32
    while t / Fraction(2) ** b >= 2 ** 32:
        b += 1
    while t / Fraction(2) ** b < 2 ** 31:
        b -= 1
    m = round(t / Fraction(2) ** b)
    if m == 2 ** 32:
        m, b = 2 ** 31, b + 1
    return m, b


def main():
    rows = [entry(e) for e in range(LO, HI + 1)]
    print("; generated by tools/gen_pow10.py -- do not edit")
    print(f"; 10^e for e = {LO}..{HI}, index e + {-LO}")
    arrays = [("p10m0", lambda m, b: m & 0xFF), ("p10m1", lambda m, b: (m >> 8) & 0xFF),
              ("p10m2", lambda m, b: (m >> 16) & 0xFF), ("p10m3", lambda m, b: m >> 24),
              ("p10bl", lambda m, b: b & 0xFF), ("p10bh", lambda m, b: (b >> 8) & 0xFF)]
    for name, f in arrays:
        vals = [f(m, b) for m, b in rows]
        print(f"{name}:")
        for i in range(0, len(vals), 8):
            print("        .byte " + ", ".join(f"${v:02x}" for v in vals[i:i + 8]))


main()
