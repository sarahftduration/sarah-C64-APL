CURSOR = 0x7F


def expected_charset(chargen):
    """The 2 KB the start-up code must build, from the 4 KB character ROM image."""
    cs = bytearray(2048)
    for dst, src, n in ROM_COPY:
        for k in range(n):
            cs[(dst + k) * 8:(dst + k) * 8 + 8] = chargen[2048 + (src + k) * 8:2048 + (src + k) * 8 + 8]
    for code, (_, rows) in GLYPHS.items():
        cs[code * 8:code * 8 + 8] = bytes(rows)
    return bytes(cs)
