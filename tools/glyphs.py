"""Charset: which ROM shapes to copy and the hand-drawn glyphs (8x8, bit 7 = leftmost pixel).

Our charset is indexed by our own character codes (ASCII plus the codes in DESIGN.md),
not by C64 screen codes. Shapes for most ASCII come from the character ROM's
lowercase/uppercase set; the ROM has no backslash, underscore, caret, grave, braces,
bar or tilde in ASCII positions, so those are drawn here along with the APL glyphs.
Drawn to match the ROM's stroke weight.
"""

# (our first code, ROM screen code of the shape, count); the ROM set is at $D800 (set 2)
ROM_COPY = [
    (0x20, 0x20, 32),      # space ! " # $ % & ' ( ) * + , - . / 0-9 : ; < = > ?
    (0x40, 0x00, 1),       # @
    (0x41, 0x41, 26),      # A-Z
    (0x5B, 27, 1),         # [
    (0x5D, 29, 1),         # ]
    (0x61, 1, 26),         # a-z
]

def art(*rows):
    """Eight strings of eight characters ('#' = pixel, leftmost = bit 7) -> the eight row bytes."""
    assert len(rows) == 8 and all(len(r) == 8 for r in rows), rows
    return [sum(0x80 >> i for i, c in enumerate(r) if c == "#") for r in rows]


