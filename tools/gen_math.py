"""Generate asm/mathprog.inc from the model's numeric programs (apl64.MATH_PROGS, MATH_CONSTS, VM_OPS)."""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import apl64

print("; generated by tools/gen_math.py from apl64.py -- do not edit")
print("; the constants (float24: exponent, sign|hi7, lo8), the programs, and the interpreter's dispatch table")
for i, name in enumerate(apl64.MATH_CONST_NAMES):
    print(f"MKC_{name.upper()} = {i}")
print("mk_table:")
for name, p in zip(apl64.MATH_CONST_NAMES, apl64.MATH_CONSTS):
    print(f"        .byte ${p >> 16:02x}, ${p >> 8 & 0xFF:02x}, ${p & 0xFF:02x}    ; {name}")
for prog_name, prog in apl64.MATH_PROGS.items():
    print(f"mp_{prog_name.lower()}:")
    for op, arg in prog:
        if op >= apl64.OP_IFLT:
            label = ("IFLT" if op < apl64.OP_IFGE else "IFGE") + f" {apl64.MATH_CONST_NAMES[arg]}, {op & 15}"
        else:
            label = apl64.VM_OPS[op]
            if label in ("LDK", "ADDK", "SUBK", "MULK", "DIVK", "RSUBK", "RDIVK"):
                label += f" {apl64.MATH_CONST_NAMES[arg]}"
            elif arg or label in ("LDS", "STS"):
                label += f" {arg}"
        print(f"        .byte {op}, {arg}    ; {label}")
print("mv_tab:")
print("        .word " + ", ".join(f"h_{n.lower()}" for n in apl64.VM_OPS))
print("mv_progs:")
print("        .word " + ", ".join(f"mp_{n.lower()}" for n in apl64.MATH_PROG_NAMES))
print("; the programs of k circle x, indexed by k + 7 for k from -7 to 7")
print("mc_tab:")
print("        .byte " + ", ".join(str(apl64.MATH_PROG_NAMES.index(apl64.CIRCLE_PROGS[k])) for k in range(-7, 8)))
