"""Generate asm/quadnames.inc from the model's quad function names (apl64.QUAD_NAMES): the tokenizer looks a
typed name up in four tables of letters (one per position, lower case, 0 past the end), token = $A0 + the index."""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import apl64

print("; generated by tools/gen_quad.py from apl64.py -- do not edit")
print(f"QUAD_COUNT = {len(apl64.QUAD_NAMES)}")
assert all(len(n) <= 4 for n in apl64.QUAD_NAMES)
for pos in range(4):
    letters = [ord(n[pos].lower()) if pos < len(n) else 0 for n in apl64.QUAD_NAMES]
    print(f"qcol{pos}: .byte " + ", ".join(f"${c:02x}" for c in letters))
print("; names: " + " ".join(apl64.QUAD_NAMES))
