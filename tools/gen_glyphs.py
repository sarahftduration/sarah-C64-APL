"""Generate asm/glyphs.inc from tools/glyphs.py."""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from glyphs import GLYPHS, ROM_COPY

print("; generated by tools/gen_glyphs.py -- do not edit")
print("; ROM shapes to copy: our first code, ROM screen code, count; ended by a zero")
print("rom_copy:")
for dst, src, n in ROM_COPY:
    print(f"        .byte ${dst:02x}, ${src:02x}, {n}")
print("        .byte 0")
print("; hand-drawn glyphs: our code, then 8 rows; ended by a zero")
print("glyph_table:")
for code in sorted(GLYPHS):
    name, rows = GLYPHS[code]
    print(f"        .byte ${code:02x}, " + ", ".join(f"${r:02x}" for r in rows) + f"    ; {name}")
print("        .byte 0")
